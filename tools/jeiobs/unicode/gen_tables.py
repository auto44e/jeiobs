#!/usr/bin/env python3
"""Generates the Unicode tables for the path-collision key (WORKSPACE_FORMAT section 12, owner
decision 3): canonical decomposition (NFD, fully recursive; Hangul is algorithmic and not in the
table), canonical combining classes, and full case folding (CaseFolding.txt status C and F).

    tools/jeiobs/unicode/gen_tables.py UCD_DIR OUT_FILE

UCD_DIR holds the files fetched by fetch-ucd.sh. OUT_FILE is a C++ include (committed); regenerate it
whenever the pinned UCD version changes and commit both together. The output is deterministic.
"""
import sys

def main():
    ucd, out = sys.argv[1], sys.argv[2]
    version = None
    decomp, ccc = {}, {}
    for line in open(f'{ucd}/UnicodeData.txt', encoding='utf-8'):
        f = line.rstrip('\n').split(';')
        cp = int(f[0], 16)
        if f[3] != '0':
            ccc[cp] = int(f[3])
        d = f[5]
        if d and not d.startswith('<'):  # canonical decompositions only
            decomp[cp] = [int(x, 16) for x in d.split()]
        # ranges (<CJK Ideograph, First>...) have no decompositions or classes: nothing to do
    fold = {}
    for line in open(f'{ucd}/CaseFolding.txt', encoding='utf-8'):
        if line.startswith('# CaseFolding-'):
            version = line.split('-')[1].split('.txt')[0]
        line = line.split('#')[0].strip()
        if not line:
            continue
        code, status, mapping = [x.strip() for x in line.split(';')[:3]]
        if status in ('C', 'F'):
            fold[int(code, 16)] = [int(x, 16) for x in mapping.split()]

    def full(cp, seen=()):
        if cp not in decomp:
            return [cp]
        r = []
        for x in decomp[cp]:
            r.extend(full(x))
        return r
    full_decomp = {cp: full(cp) for cp in decomp}

    def emit_map(name, mapping):
        keys = sorted(mapping)
        data, rows = [], []
        for k in keys:
            rows.append((k, len(data), len(mapping[k])))
            data.extend(mapping[k])
        lines = [f'// {len(rows)} entries', f'inline constexpr std::uint32_t k{name}Data[] = {{']
        for i in range(0, len(data), 12):
            lines.append('\t' + ', '.join(f'0x{x:X}' for x in data[i:i + 12]) + ',')
        lines.append('};')
        lines.append(f'inline constexpr MapRow k{name}Rows[] = {{')
        for k, off, n in rows:
            lines.append(f'\t{{0x{k:X}, {off}, {n}}},')
        lines.append('};')
        return '\n'.join(lines)

    ccc_rows = sorted(ccc.items())
    body = [
        '// Generated by tools/jeiobs/unicode/gen_tables.py from the Unicode Character Database',
        f'// version {version} (UnicodeData.txt, CaseFolding.txt). Do not edit.',
        '// Unicode data: Copyright (c) 1991-2026 Unicode, Inc. Unicode License v3; see',
        '// shared/jeiobs-workspace/third_party/unicode/LICENSE.',
        '// clang-format off',
        f'inline constexpr const char kUnicodeVersion[] = "{version}";',
        emit_map('Decomposition', full_decomp),
        emit_map('CaseFold', fold),
        f'// {len(ccc_rows)} entries',
        'inline constexpr ClassRow kCombiningClassRows[] = {',
        *[f'\t{{0x{cp:X}, {c}}},' for cp, c in ccc_rows],
        '};',
        '// clang-format on',
        '',
    ]
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(body))

main()
